import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'fs';
import os from 'os';
import path from 'path';
import { StudyHubStorage } from '../server/storage.ts';

const rootDir = process.cwd();

test('Electron main.ts uses pure loadFile + IPC with zero localhost/HTTP server', () => {
  const mainSrc = fs.readFileSync(path.join(rootDir, 'electron', 'main.ts'), 'utf-8');
  assert.match(mainSrc, /mainWindow\.loadFile\(/);
  assert.doesNotMatch(mainSrc, /http:\/\/127\.0\.0\.1|http:\/\/localhost|loadURL\(|spawn\(/);
});

test('Electron main.cjs bundled output exists, loads local dist/index.html, and includes electron-updater IPC', () => {
  const mainCjsPath = path.join(rootDir, 'electron', 'main.cjs');
  assert.equal(fs.existsSync(mainCjsPath), true, 'electron/main.cjs must be compiled');
  const bundle = fs.readFileSync(mainCjsPath, 'utf-8');
  assert.match(bundle, /loadFile\(/);
  assert.match(bundle, /studyhub:checkForUpdates/);
  assert.match(bundle, /studyhub:downloadUpdate/);
  assert.match(bundle, /studyhub:quitAndInstall/);
  assert.doesNotMatch(bundle, /\/api\/vocab|\/api\/quizzes|express\(\)/);
});

test('Every IPC channel in electron/preload.cjs is handled in electron/main.ts', () => {
  const mainSrc = fs.readFileSync(path.join(rootDir, 'electron', 'main.ts'), 'utf-8');
  const preloadSrc = fs.readFileSync(path.join(rootDir, 'electron', 'preload.cjs'), 'utf-8');

  const invokedChannels = [...preloadSrc.matchAll(/ipcRenderer\.invoke\(\s*'([^']+)'/g)].map(
    (m) => m[1],
  );
  const handledChannels = new Set(
    [...mainSrc.matchAll(/ipcMain\.handle\(\s*'([^']+)'/g)].map((m) => m[1]),
  );

  assert.ok(invokedChannels.length >= 20, 'Expected at least 20 IPC channels including auto-updater');
  for (const ch of invokedChannels) {
    assert.ok(handledChannels.has(ch), `Missing ipcMain.handle for channel: ${ch}`);
  }
});

test('GitHub Releases auto-update configuration matches electron-updater requirements', () => {
  const pkg = JSON.parse(fs.readFileSync(path.join(rootDir, 'package.json'), 'utf-8'));
  assert.ok(pkg.dependencies['electron-updater'], 'electron-updater must be in dependencies');
  assert.equal(pkg.build?.win?.verifyUpdateCodeSignature, false);
  assert.equal(pkg.build?.nsis?.artifactName, 'StudyHub-Setup-${version}.exe');

  const workflow = fs.readFileSync(
    path.join(rootDir, '.github', 'workflows', 'release-windows.yml'),
    'utf-8',
  );
  assert.match(workflow, /provider:\s*'github'/);
  assert.match(workflow, /release\/latest\.yml/);
  assert.match(workflow, /app-update\.yml/);
  assert.match(workflow, /make_latest:\s*true/);
});

test('Fresh StudyHub data directory has zero preset examples and auto-generates AGENT_GUIDE.md', async () => {
  const tmpDir = fs.mkdtempSync(path.join(os.tmpdir(), 'studyhub-clean-'));
  const prevEnv = process.env.STUDYHUB_DATA_DIR;
  process.env.STUDYHUB_DATA_DIR = tmpDir;

  const store = new StudyHubStorage();
  try {
    assert.equal(store.readVocabFile().words.length, 0, 'vocab.json must start empty with zero preset words');
    assert.equal(store.listQuizzes().length, 0, 'quizzes/ must start empty with zero preset quizzes');
    assert.equal(store.listResults().length, 0, 'results/ must start empty');

    const guidePath = path.join(tmpDir, 'AGENT_GUIDE.md');
    assert.equal(fs.existsSync(guidePath), true, 'AGENT_GUIDE.md must be auto-generated in dataDir');
    const guideText = fs.readFileSync(guidePath, 'utf-8');
    assert.match(guideText, /quizzes\/\*\.json/);
    assert.match(guideText, /vocab_inbox\/\*\.json/);

    // Verify Agent can drop a minimal quiz and inbox batch directly
    const quizPath = path.join(tmpDir, 'quizzes', 'agent-q1.json');
    fs.writeFileSync(
      quizPath,
      JSON.stringify({
        quiz_id: 'agent-q1',
        title: 'Agent Check',
        subject: 'ICT',
        questions: [
          {
            id: 'q1',
            stem: 'Is this generated by an agent?',
            options: ['True', 'False'],
            correct_index: 0,
          },
        ],
      }),
    );
    const loaded = store.listQuizzes();
    assert.equal(loaded.length, 1);
    assert.equal(loaded[0].pass_rate, 80);
    assert.equal(loaded[0].questions[0].type, 'true_false');

    const inboxRes = store.dropInboxFile('agent_batch.json', {
      words: [{ word: 'latency', meaning_zh: '延迟', subject: 'ICT' }],
    });
    assert.equal(inboxRes.addedCount, 1);
    assert.equal(fs.existsSync(path.join(tmpDir, 'vocab_inbox', 'agent_batch.json')), false);
  } finally {
    await store.close();
    if (prevEnv === undefined) {
      delete process.env.STUDYHUB_DATA_DIR;
    } else {
      process.env.STUDYHUB_DATA_DIR = prevEnv;
    }
    fs.rmSync(tmpDir, { recursive: true, force: true });
  }
});
